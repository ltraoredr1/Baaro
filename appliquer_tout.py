for path, b64 in FILES.items():
    full = os.path.join(ROOT, path)
    if not os.path.isdir(os.path.dirname(full)):
        fail(f"dossier introuvable : {os.path.dirname(path)} (lance le script depuis la racine du dépôt)")
    data = zlib.decompress(base64.b64decode("".join(b64.split()))).decode("utf-8")
    write(full, data)
    print("Écrit :", path)


def sub_once(s, pattern, repl, label, flags=0):
    new, n = re.subn(pattern, repl, s, count=1, flags=flags)
    if n != 1:
        fail(f"motif introuvable : {label}")
    return new


