ROOT = os.getcwd()
SRC = os.path.join(ROOT, "src")


def fail(msg):
    print("ERREUR :", msg)
    sys.exit(1)


def read(p):
    with open(p, encoding="utf-8") as f:
        return f.read()


def write(p, s):
    with open(p, "w", encoding="utf-8") as f:
        f.write(s)


def find_file(pattern):
    out = subprocess.run(
        ["grep", "-rlE", pattern, SRC, "--include=*.js", "--include=*.jsx", "--include=*.ts", "--include=*.tsx"],
        capture_output=True, text=True,
    ).stdout.split()
    if len(out) != 1:
        fail(f"fichier introuvable ou ambigu pour « {pattern} » : {out}")
    return out[0]


def rel_lib(from_file, name):
    r = os.path.relpath(os.path.join(SRC, "lib", name), os.path.dirname(from_file))
    r = r.replace(os.sep, "/")
    return r if r.startswith(".") else "./" + r


