p = find_file(r"export function AppProvider")
s = read(p)
if "wipeLocalPrivateData" in s:
    print("AppContext : déjà patché.")
else:
    imp = (f'import {{ wipeSecureStorage }} from "{rel_lib(p, "messageOutbox.js")}";\n'
           f'import {{ clearSmsNumbers }} from "{rel_lib(p, "smsFallback.js")}";\n')
    s = sub_once(s, r'(import \{ getDeviceId \} from [^\n]+\n)', lambda m: m.group(1) + imp, "import getDeviceId")
    fn = ("async function wipeLocalPrivateData() {\n"
          "  try {\n    await wipeSecureStorage();\n  } catch {}\n"
          "  clearSmsNumbers();\n}\n\n")
    s = sub_once(s, r'export function AppProvider', lambda m: fn + "export function AppProvider", "AppProvider")
    s = sub_once(s, r'(\n[ \t]*)safeRemove\(PROFILE_CACHE_KEY\);',
                 lambda m: m.group(0) + m.group(1) + "await wipeLocalPrivateData();", "logout")
    s = sub_once(s, r'(if \(!mounted\) return;\s*)(if \(nextSession\?\.user\?\.is_anonymous\) \{)',
                 lambda m: m.group(1) + 'if (event === "SIGNED_OUT") void wipeLocalPrivateData();\n      ' + m.group(2),
                 "onAuthStateChange")
    write(p, s)
    print("AppContext : patché ->", os.path.relpath(p, ROOT))

